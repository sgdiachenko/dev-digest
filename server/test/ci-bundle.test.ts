describe('memory.jsonl (AC-40)', () => {
  it('writes one MemoryItem per line, null confidence as 0, at most 200', () => {
    const items = Array.from({ length: 205 }, (_, i) => mem({ content: `m${i}` }));
    items[0] = mem({ content: 'first', confidence: null as unknown as number });
    const lines = memoryJsonl(items).trimEnd().split('\n');
    expect(lines).toHaveLength(200);
    expect(JSON.parse(lines[0]!)).toMatchObject({ content: 'first', confidence: 0 });
    expect(JSON.parse(lines[199]!).content).toBe('m199');
  });
});

describe('workflow (AC-42–49, AC-103, AC-132)', () => {
  const wf = workflowYaml(['opened', 'synchronize'], ['security-reviewer', 'perf']);
  const doc = parse(wf) as {
    on: Record<string, { types: string[] }>;
    permissions: Record<string, string>;
    concurrency: { group: string; 'cancel-in-progress': boolean };
    jobs: { review: { 'timeout-minutes': number; steps: Record<string, unknown>[] } };
  };

  it('triggers only on pull_request with the given union, never pull_request_target', () => {
    expect(Object.keys(doc.on)).toEqual(['pull_request']);
    expect(doc.on.pull_request!.types).toEqual(['opened', 'synchronize']);
    expect(wf).not.toContain('pull_request_target');
  });

  it('declares exactly the two permissions', () => {
    expect(doc.permissions).toEqual({ contents: 'read', 'pull-requests': 'write' });
  });

  it('has a per-PR concurrency group with cancel-in-progress and a 10 minute timeout', () => {
    expect(doc.concurrency).toEqual({
      group: 'devdigest-${{ github.event.pull_request.number }}',
      'cancel-in-progress': true,
    });
    expect(doc.jobs.review['timeout-minutes']).toBe(10);
  });

  it('pins every action by full SHA with the version as a trailing comment', () => {
    const uses = wf.split('\n').filter((l) => l.includes('uses:'));
    expect(uses.length).toBeGreaterThanOrEqual(4);
    for (const l of uses) expect(l).toMatch(/uses: [\w-]+\/[\w-]+@[0-9a-f]{40} # v\d+\.\d+\.\d+$/);
    expect(wf).toContain(`actions/checkout@${CI_ACTION_PINS.checkout.sha} # ${CI_ACTION_PINS.checkout.version}`);
    expect(wf).toContain(`actions/setup-node@${CI_ACTION_PINS.setupNode.sha} # ${CI_ACTION_PINS.setupNode.version}`);
    expect(wf).toContain(
      `actions/upload-artifact@${CI_ACTION_PINS.uploadArtifact.sha} # ${CI_ACTION_PINS.uploadArtifact.version}`,
    );
  });

  it('sets up Node 24 and starts the runner as node .devdigest/runner/index.js', () => {
    expect(wf).toContain('node-version: "24"');
    expect(wf).toContain('run: node .devdigest/runner/index.js');
  });

  it('passes the key to the runner step only from secrets', () => {
    const steps = doc.jobs.review.steps as { env?: Record<string, string>; run?: string }[];
    const runner = steps.find((s) => s.run === 'node .devdigest/runner/index.js')!;
    expect(runner.env!.OPENROUTER_API_KEY).toBe('${{ secrets.OPENROUTER_API_KEY }}');
    expect(wf.match(/secrets\.OPENROUTER_API_KEY/g)).toHaveLength(1);
    expect(wf.match(/secrets\.\w+/g)!.sort()).toEqual(['secrets.GITHUB_TOKEN', 'secrets.OPENROUTER_API_KEY']);
  });

  it('uploads one always() artifact per installed agent slug', () => {
    const uploads = (doc.jobs.review.steps as { uses?: string; if?: string; with?: Record<string, string> }[]).filter(
      (s) => s.uses?.startsWith('actions/upload-artifact@'),
    );
    expect(uploads.map((u) => u.with!.name)).toEqual(['devdigest-result-perf', 'devdigest-result-security-reviewer']);
    for (const u of uploads) expect(u.if).toBe('always()');
    expect(uploads[1]!.with!.path).toBe('.devdigest-results/security-reviewer/devdigest-result.json');
  });

  it('ends with an always() step that fails when a manifest has no result file', () => {
    const steps = doc.jobs.review.steps as { if?: string; run?: string }[];
    const last = steps[steps.length - 1]!;
    expect(last.if).toBe('always()');
    expect(last.run).toContain('.devdigest/agents/*.yaml');
    expect(last.run).toContain('.devdigest-results/$slug/devdigest-result.json');
    expect(last.run).toContain('exit $missing');
  });

  it('expands no PR-controlled data in any run: line', () => {
    const steps = doc.jobs.review.steps as { run?: string }[];
    for (const s of steps) if (s.run) expect(s.run).not.toContain('${{');
    expect(wf).not.toMatch(/github\.event\.pull_request\.(title|body|head)/);
    expect(wf).not.toContain('github.head_ref');
  });

  it('refuses an unsafe slug', () => {
    expect(() => workflowYaml(['opened'], ['x"; rm -rf /'])).toThrow();
  });
});

describe('buildBundle options', () => {
  it('uses the workflow override verbatim and keeps every other file generated (AC-130)', () => {
    const b = buildBundle(input({ workflowOverride: 'name: mine\n' }), 'acme/api');
    expect(fileOf(b, CI_PATHS.WORKFLOW).contents).toBe('name: mine\n');
    expect(fileOf(b, '.devdigest/runner/index.js').contents).toBe('// index\n');
  });

  it('carries no secret and states the trust model in the PR body (AC-50, AC-51, AC-167)', () => {
    const b = buildBundle(input(), 'acme/api');
    expect(b.prTitle).toBe('Add DevDigest CI review');
    expect(b.prBody).toContain('push a branch');
    expect(b.prBody).toContain('OPENROUTER_API_KEY');
    expect(b.prBody).toMatch(/forks? .*skipped/i);
    expect(b.prBody).toContain('.devdigest/');
    expect(b.prBody).toContain("that PR's own CI run uses the changed files");
    for (const f of b.files) expect(f.contents).not.toMatch(/sk-or-|ghp_|github_pat_/);
  });
});
