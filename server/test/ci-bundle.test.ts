/**
 * T1 — the pure CI bundle generator (S2.1): manifest, skills, memory, workflow, PR body.
 */
import { describe, it, expect } from 'vitest';
import { parse } from 'yaml';
import { AgentManifest, CI_ACTION_PINS, CI_PATHS } from '@devdigest/shared';
import type { MemoryItem } from '@devdigest/shared';
import {
  buildBundle,
  memoryJsonl,
  skillFileContents,
  workflowYaml,
  type BundleInput,
} from '../src/modules/ci/bundle.js';
import { gitBlobSha, sha256Hex, slugify, uniqueSlugs } from '../src/modules/ci/helpers.js';
import type { CiAgent } from '../src/modules/ci/types.js';

const agent: CiAgent = {
  id: 'a1',
  name: 'Security Reviewer',
  version: 4,
  provider: 'openrouter',
  model: 'anthropic/claude-sonnet-4',
  systemPrompt: 'Review for security.\nBe terse: "quote" and colon: ok.',
  strategy: 'auto',
  ciFailOn: 'warning',
};

function input(over: Partial<BundleInput> = {}): BundleInput {
  return {
    agent,
    skills: [],
    memory: [],
    postAs: 'github_review',
    triggers: ['opened', 'synchronize', 'reopened'],
    workflowTriggers: ['opened', 'synchronize', 'reopened'],
    installedSlugs: ['security-reviewer'],
    runnerFiles: [
      { name: 'index.js', contents: '// index\n' },
      { name: '300.index.js', contents: '// chunk\n' },
      { name: 'package.json', contents: '{"type":"module"}\n' },
    ],
    workflowOverride: null,
    ...over,
  };
}

const mem = (over: Partial<MemoryItem> = {}): MemoryItem => ({
  content: 'Use zod',
  scope: 'global',
  kind: 'convention',
  confidence: 0.8,
  sources: [{ context: 'pr' }],
  ...over,
});

function fileOf(bundle: ReturnType<typeof buildBundle>, path: string) {
  const f = bundle.files.find((x) => x.path === path);
  if (!f) throw new Error(`missing ${path}`);
  return f;
}

describe('slug helpers', () => {
  it('slugifies to a path-safe name and never returns empty', () => {
    expect(slugify('Security Reviewer!')).toBe('security-reviewer');
    expect(slugify('../../etc/passwd')).toBe('etc-passwd');
    expect(slugify('!!!')).toBe('agent');
  });

  it('suffixes repeated skill slugs with -2, -3', () => {
    expect(uniqueSlugs(['Lint', 'lint', 'LINT', 'Other'])).toEqual(['lint', 'lint-2', 'lint-3', 'other']);
  });

  it('computes the git blob sha GitHub reports', () => {
    // `printf 'hello\n' | git hash-object --stdin`
    expect(gitBlobSha('hello\n')).toBe('ce013625030ba8dba906f756967f9e9ca394464a');
  });
});

describe('bundle files (AC-146, AC-184)', () => {
  it('lists manifest, skills, memory, both runner files and the workflow, in that order', () => {
    const b = buildBundle(
      input({
        skills: [
          { name: 'Auth rules', source: 'manual', body: 'a' },
          { name: 'SQL rules', source: 'imported_url', body: 'b' },
        ],
      }),
      'acme/api',
    );
    expect(b.files.map((f) => f.path)).toEqual([
      '.devdigest/agents/security-reviewer.yaml',
      '.devdigest/skills/auth-rules.md',
      '.devdigest/skills/sql-rules.md',
      '.devdigest/memory.jsonl',
      '.devdigest/runner/index.js',
      '.devdigest/runner/300.index.js',
      '.devdigest/runner/package.json',
      '.github/workflows/devdigest-review.yml',
    ]);
    expect(b.files.filter((f) => f.editable).map((f) => f.path)).toEqual([CI_PATHS.WORKFLOW]);
  });

  it('has no skill file when the agent has no enabled skill (EC-16)', () => {
    const b = buildBundle(input(), 'acme/api');
    expect(b.files.some((f) => f.path.startsWith('.devdigest/skills/'))).toBe(false);
    expect(b.skills).toEqual([]);
    expect(fileOf(b, '.devdigest/memory.jsonl').contents).toBe('');
  });

  it('dedupes skill slugs and records the sha256 of the generated bytes', () => {
    const b = buildBundle(
      input({
        skills: [
          { name: 'Lint', source: 'manual', body: 'one' },
          { name: 'lint', source: 'extracted', body: 'two' },
        ],
      }),
      'acme/api',
    );
    expect(b.skills.map((s) => s.slug)).toEqual(['lint', 'lint-2']);
    const f = fileOf(b, '.devdigest/skills/lint-2.md');
    expect(b.skills[1]!.sha256).toBe(sha256Hex(f.contents));
    expect(f.contents).toBe('---\nsource: extracted\n---\ntwo\n');
  });

  it('writes the source front matter before the body', () => {
    expect(skillFileContents({ name: 'x', source: 'manual', body: 'body\n' })).toBe(
      '---\nsource: manual\n---\nbody\n',
    );
  });
});

